#!/usr/bin/env node
/**
 * Turns packages/web/dist into a TypeScript module the agent can serve from
 * memory, so a standalone binary ships its own UI.
 *
 *   node scripts/embed-web.mjs
 *
 * Missing web build is not an error: the module is written empty so a fresh
 * clone still typechecks and builds the agent.
 */
import { createHash } from 'node:crypto'
import { gzipSync, constants as zlibConstants } from 'node:zlib'
import { existsSync, readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const distDir = path.join(root, 'packages/web/dist')
const outFile = path.join(root, 'packages/agent/src/web-assets.ts')

const MIME_BY_EXT = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.avif': 'image/avif',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.otf': 'font/otf',
  '.eot': 'application/vnd.ms-fontobject',
  '.wasm': 'application/wasm',
  '.webmanifest': 'application/manifest+json',
  '.xml': 'application/xml',
}

const HEADER = `// Generated by scripts/embed-web.mjs — do not edit by hand.
// Only the empty form belongs in git: never commit a populated version.
`

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else if (entry.isFile()) out.push(full)
  }
  return out
}

function emit(entries, buildId) {
  const body = entries
    .map(([url, asset]) => `  ${JSON.stringify(url)}: { mime: ${JSON.stringify(asset.mime)}, gzip: '${asset.gzip}' },`)
    .join('\n')
  const map = entries.length === 0 ? '{}' : `{\n${body}\n}`
  writeFileSync(
    outFile,
    `${HEADER}
export interface EmbeddedAsset {
  mime: string
  /** base64 of the gzipped bytes */
  gzip: string
}

export const WEB_ASSETS: Record<string, EmbeddedAsset> = ${map}

export const WEB_BUILD: string | null = ${buildId === null ? 'null' : `'${buildId}'`}
`,
  )
}

if (!existsSync(distDir) || !statSync(distDir).isDirectory()) {
  emit([], null)
  console.log(`embed-web: no ${path.relative(root, distDir)}, wrote an empty ${path.relative(root, outFile)}`)
  process.exit(0)
}

const files = walk(distDir).sort()
const hash = createHash('sha256')
const entries = []
let raw = 0
let packed = 0

for (const file of files) {
  const bytes = readFileSync(file)
  const url = `/${path.relative(distDir, file).split(path.sep).join('/')}`
  const gz = gzipSync(bytes, { level: zlibConstants.Z_BEST_COMPRESSION })
  hash.update(url).update(bytes)
  raw += bytes.length
  packed += gz.length
  entries.push([
    url,
    { mime: MIME_BY_EXT[path.extname(file).toLowerCase()] ?? 'application/octet-stream', gzip: gz.toString('base64') },
  ])
}

const buildId = entries.length > 0 ? hash.digest('hex').slice(0, 12) : null
emit(entries, buildId)

const kb = (n) => `${(n / 1024).toFixed(1)} KB`
console.log(
  `embed-web: ${entries.length} file(s), ${kb(raw)} raw → ${kb(packed)} gzipped, build ${buildId ?? 'none'}`,
)
console.log(`  → ${path.relative(root, outFile)}`)
